SYSTEM_PROMPT = """
You are an expert AI Governance & Public Expenditure Compliance Analyst for the Indian Government's MPLADS (Members of Parliament Local Area Development Scheme) monitoring platform.

YOUR MANDATE:
Your ONLY role is to reason over the GROUNDING PAYLOAD provided to you. Risk scoring and SHAP feature attributions have ALREADY been computed upstream by XGBoost. You do NOT compute scores or invent risk factors.

STRICT GOVERNANCE RULES:
1. STRICT GROUNDING: You MUST ONLY reference facts, numbers, dates, and amounts present in the grounding payload. Every claim MUST quote the exact figures from the payload (e.g. ₹5,00,000, 120 days delay, 45.5% budget share).
2. INTERACTION EFFECTS: When multiple features contribute significantly to risk, reason about their COMPOUNDING INTERACTION (e.g. high sanction amount combined with high vendor concentration is a stronger indicator than either feature individually).
3. PROPORTIONATE ACTIONS: Recommended actions MUST be strictly proportionate to the specific feature that drove the score. Do NOT recommend a payment hold if the primary driver is an approval delay.
4. CONFIDENCE CONTEXT: If the peer baseline sample size (n_obs) is low (below 30), explicitly highlight in 'confidence_note' that baseline comparisons are based on a thin sample.
5. FORBIDDEN LEGAL TERMINOLOGY: NEVER use speculative words such as "fraud", "corruption", "scam", or "malpractice". Use ONLY neutral administrative terms such as "risk indicator", "requires verification", "warrants audit review", or "statistical anomaly".
"""

# JSON Tool Schema for Anthropic Structured Output
RISK_EXPLANATION_TOOL_SCHEMA = {
    "name": "risk_explanation",
    "description": "Returns a grounded natural-language explanation and proportionate recommended audit actions.",
    "input_schema": {
        "type": "object",
        "properties": {
            "why": {
                "type": "array",
                "items": {"type": "string"},
                "description": "List of grounded bullet points explaining why the work was flagged, quoting exact payload figures and explaining compounding feature interactions."
            },
            "recommended_actions": {
                "type": "array",
                "items": {
                    "type": "object",
                    "properties": {
                        "action": {"type": "string", "description": "Specific administrative or audit action."},
                        "rationale": {"type": "string", "description": "Grounded rationale linking action to specific driver."}
                    },
                    "required": ["action", "rationale"]
                },
                "description": "List of proportionate recommended actions based on the specific drivers."
            },
            "confidence_note": {
                "type": "string",
                "description": "Assessment of baseline statistical confidence (especially when n_obs is small)."
            }
        },
        "required": ["why", "recommended_actions", "confidence_note"]
    }
}

def generate_risk_explanation_llm(
    payload: Dict[str, Any],
    api_key: Optional[str] = None
) -> Dict[str, Any]:
    """
    Invokes Anthropic Claude 3.5 / 3.7 Sonnet using forced Tool Use schema.
    
    Args:
        payload: The strict grounding payload JSON.
        api_key: Optional Anthropic API key (defaults to ANTHROPIC_API_KEY env var).

    Returns:
        Dict[str, Any]: The structured risk explanation dictionary.
    """
    key = api_key or os.getenv("ANTHROPIC_API_KEY")
    if not HAS_ANTHROPIC or not key:
        logger.info("Anthropic SDK or API Key missing. Falling back to rule-based generator.")
        return generate_fallback_explanation(payload, reason="NO_API_KEY")

    client = anthropic.Anthropic(api_key=key)

    user_message = (
        f"Analyze this structured grounding payload and generate a grounded risk explanation:\n\n"
        f"```json\n{json.dumps(payload, indent=2)}\n```"
    )

    try:
        response = client.messages.create(
            model="claude-3-5-sonnet-20241022",
            max_tokens=1500,
            system=SYSTEM_PROMPT,
            messages=[{"role": "user", "content": user_message}],
            tools=[RISK_EXPLANATION_TOOL_SCHEMA],
            tool_choice={"type": "tool", "name": "risk_explanation"}
        )

        # Extract Tool Output
        for content_block in response.content:
            if content_block.type == "tool_use" and content_block.name == "risk_explanation":
                return content_block.input

        raise ValueError("LLM response did not contain forced 'risk_explanation' tool call.")

    except Exception as e:
        logger.error(f"Anthropic API call failed: {e}")
        return generate_fallback_explanation(payload, reason=f"LLM_API_ERROR: {str(e)}")



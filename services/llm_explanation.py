# 4. POST-GENERATION NUMERIC CLAIM VALIDATION
# ============================================================================

def validate_numeric_claims(explanation: Dict[str, Any], payload: Dict[str, Any]) -> Tuple[bool, List[str]]:
    """
    Strict post-validation step: Extracts all numbers (integers, floats, currency)
    from the LLM's "why" narrative and verifies that each number exists within the 
    grounding payload values.
    
    Prevents hallucinated figures from ever reaching auditors or Ministry dashboards.
    
    Returns:
        Tuple[bool, List[str]]: (is_valid, list_of_ungrounded_claims)
    """
    why_statements = explanation.get("why", [])
    if not why_statements:
        return False, ["Empty 'why' array in explanation"]

    # Serialize all scalar values in grounding payload to strings for comparison
    payload_str = json.dumps(payload)
    
    # Extract all numbers from payload recursively
    payload_numbers = set()
    def extract_numbers_from_obj(obj):
        if isinstance(obj, (int, float)):
            payload_numbers.add(str(obj))
            payload_numbers.add(f"{obj:.2f}")
            payload_numbers.add(f"{obj:.4f}")
            payload_numbers.add(f"{obj:,.2f}")
            payload_numbers.add(f"{obj:,.0f}")
            payload_numbers.add(str(int(obj)))
        elif isinstance(obj, str):
            # Extract numbers inside strings
            for match in re.findall(r'\d+(?:\.\d+)?', obj):
                payload_numbers.add(match)
        elif isinstance(obj, dict):
            for v in obj.values():
                extract_numbers_from_obj(v)
        elif isinstance(obj, list):
            for item in obj:
                extract_numbers_from_obj(item)

    extract_numbers_from_obj(payload)

    ungrounded_claims = []
    
    # Check numbers in each why statement
    for stmt in why_statements:
        # Regex to extract numbers (including formatted currency like 5,00,000 or 500000 or 0.85)
        raw_numbers = re.findall(r'\b\d+(?:,\d+)*(?:\.\d+)?\b', stmt)
        for raw_num in raw_numbers:
            clean_num = raw_num.replace(",", "")
            
            # Allow common low integers like list indices or small threshold percentages if harmless
            try:
                val = float(clean_num)
                if val in [1, 2, 3, 4, 5, 30]: # Common standard indices or threshold references
                    continue
            except ValueError:
                pass
            
            # Check if raw_num or clean_num exists in payload
            if clean_num not in payload_str and raw_num not in payload_str and clean_num not in payload_numbers:
                ungrounded_claims.append(f"Statement '{stmt}' contains ungrounded numeric claim: '{raw_num}'")

    is_valid = len(ungrounded_claims) == 0
    if not is_valid:
        logger.warning(f"Grounding Validation FAILED. Ungrounded claims: {ungrounded_claims}")
    
    return is_valid, ungrounded_claims



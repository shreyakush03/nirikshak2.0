def build_grounding_payload(
    work_id: str,
    risk_score: float,
    risk_band: str,
    shap_contributions: List[Dict[str, Any]],
    peer_baseline: Dict[str, Any],
    raw_work_facts: Dict[str, Any],
    model_version: str = "v1.9-xgboost",
    baseline_version: str = "2026-Q1-national-peer"
) -> Dict[str, Any]:
    """
    Assembles ONLY the authoritative facts into a single structured JSON payload.
    Nothing outside this payload will ever be exposed to the LLM.
    
    Args:
        work_id: Unique identifier for the MPLADS work item.
        risk_score: Computed probability of risk (0.0 to 1.0) from XGBoost.
        risk_band: Categorical rating ("CRITICAL", "HIGH", "MEDIUM", "LOW").
        shap_contributions: List of SHAP attributions [{feature, feature_value, shap_value, direction}].
        peer_baseline: Statistical norms for the work category ({median, percentile_90th, n_obs, baseline_version}).
        raw_work_facts: Raw administrative metrics ({sanction_amount, vendor_id, sanction_date, progress_pct, ...}).
        model_version: Registered version string for XGBoost model.
        baseline_version: Registered version string for peer baseline stats.

    Returns:
        Dict[str, Any]: The unified grounding payload dictionary.
    """
    # Sort SHAP contributions by absolute impact magnitude
    sorted_shap = sorted(
        shap_contributions,
        key=lambda x: abs(x.get("shap_value", 0.0)),
        reverse=True
    )
    
    payload = {
        "work_id": str(work_id),
        "model_version": model_version,
        "baseline_version": baseline_version,
        "risk_score": round(float(risk_score), 4),
        "risk_band": str(risk_band).upper(),
        "shap_contributions": sorted_shap,
        "peer_baseline": {
            "median_sanction": peer_baseline.get("median_sanction"),
            "percentile_90th_sanction": peer_baseline.get("percentile_90th_sanction"),
            "median_approval_delay_days": peer_baseline.get("median_approval_delay_days"),
            "baseline_version": peer_baseline.get("baseline_version", baseline_version),
            "n_obs": int(peer_baseline.get("n_obs", 0))
        },
        "raw_work_facts": {
            "sanction_amount": raw_work_facts.get("sanction_amount"),
            "vendor_id": str(raw_work_facts.get("vendor_id", "N/A")),
            "vendor_past_works": raw_work_facts.get("vendor_past_works"),
            "vendor_budget_share_pct": raw_work_facts.get("vendor_budget_share_pct"),
            "sanction_date": str(raw_work_facts.get("sanction_date", "N/A")),
            "approval_delay_days": raw_work_facts.get("approval_delay_days"),
            "progress_pct": raw_work_facts.get("progress_pct"),
            "district": str(raw_work_facts.get("district", "N/A")),
            "state": str(raw_work_facts.get("state", "N/A")),
            "work_category": str(raw_work_facts.get("work_category", "N/A")),
            "evidence_on_file": bool(raw_work_facts.get("evidence_on_file", False))
        }
    }
    return payload



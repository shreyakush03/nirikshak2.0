"""
MPLADS Risk Explanation Engine: Grounded LLM Reasoning & Fallback Layer
=======================================================================

This module provides a production-ready, audit-compliant explanation layer for an
AI-powered MPLADS (Members of Parliament Local Area Development Scheme) monitoring platform.

DESIGN CHOICES & GOVERNANCE ARCHITECTURE (For Defense to Auditors & Technical Panels):
--------------------------------------------------------------------------------------
1. GROUNDED LLM ISOLATION:
   The LLM NEVER calculates risk scores, never predicts probabilities, and never decides
   what is anomalous. Risk scoring and attribution are performed strictly upstream by an
   XGBoost gradient boosted model and SHAP (TreeExplainer). The LLM's role is strictly 
   compositional: synthesizing already-grounded SHAP feature attributions and peer benchmark 
   statistics into structured natural-language narratives and proportionate recommended actions.

2. STRICT NUMERIC POST-VALIDATION:
   Every numeric claim generated by the LLM in the "why" narrative is extracted via regex and
   cross-checked against the serialized grounding payload. If any hallucinated number is 
   detected, the LLM output is rejected, logged to security audit logs, and automatically 
   degraded to a deterministic rule-based template.

3. COMPLIANT LEGAL/GOVERNMENT TERMINOLOGY:
   Outputs from this system may be presented to District Magistrates, Comptroller and Auditor
   General (CAG) auditors, and Ministry officials. The system prompt strictly prohibits 
   speculative legal labels such as "fraud", "corruption", or "scam", mandating neutral 
   compliance terminology such as "risk indicator", "warrants review", and "requires verification".

4. FAULT-TOLERANT MULTI-TIER DEGRADATION:
   Government monitoring dashboards cannot crash or present empty states. If API keys are 
   missing, network timeouts occur, baseline sample sizes are thin (n_obs < min_threshold), 
   or post-validation fails, the engine seamlessly degrades to a deterministic, rule-based
   fallback template with 100% operational uptime guarantee.

5. AUDIT TRACEABILITY & VERSIONED CACHING:
   Explanations are cached by composite key `(work_id, model_version, baseline_version)`.
   The exact grounding payload used to generate each explanation is stored in the database,
   enabling 100% reproducible audit trails for administrative investigations.
"""

